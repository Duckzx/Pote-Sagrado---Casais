/**
 * Optimized currency formatter for BRL.
 * Initializing Intl.NumberFormat is expensive; reusing a singleton is more performant.
 */
export const BRL = new Intl.NumberFormat('pt-BR', {
  style: 'currency',
  currency: 'BRL',
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

/**
 * Formats a number to BRL currency string using the cached formatter.
 */
export const formatBRL = (value: number): string => BRL.format(value);

export const maskCurrency = (value: string): string => {
  const digits = value.replace(/\D/g, '');
  if (!digits) return '';
  const numberValue = Number(digits) / 100;
  return BRL.format(numberValue);
};

export const parseCurrencyString = (value: string): number => {
  const digits = value.replace(/\D/g, '');
  return Number(digits) / 100;
};
